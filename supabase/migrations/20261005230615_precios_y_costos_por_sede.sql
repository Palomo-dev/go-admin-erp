-- ---------------------------------------------------------------------
-- 2. Resolución del vigente (precio y costo)
--
-- Orden para (producto, sede, instante):
--   1) fila vigente de la sede (product_branch_*)           origen 'sede'
--   2) fila vigente general (product_prices/product_costs)  origen 'general'
--   3) si p_heredar_padre y el producto es una variante:
--      lo mismo con el padre                                 'padre_sede' / 'padre_general'
-- Vigente = effective_from <= instante < coalesce(effective_to, infinito);
-- entre varias, la de effective_from más reciente y, a igualdad, id mayor
-- (la regla de fn_pos_precio_base_vigente y de src/lib/pos/precioVigente.ts).
--
-- SECURITY INVOKER: con la sesión de un usuario aplica la RLS de las cuatro
-- tablas (un producto de otra organización sale sin precio: no hay fuga);
-- llamadas desde funciones SECURITY DEFINER (validación del POS, recetas)
-- leen como su dueño. Una sede de otra organización no tiene filas (el
-- trigger de coherencia lo impide), así que resolvería al general.
-- ---------------------------------------------------------------------
create or replace function public.fn_precios_vigentes_lote(
  p_organization_id integer,
  p_branch_id integer,
  p_product_ids integer[],
  p_at timestamptz default null,
  p_heredar_padre boolean default false
)
returns table (
  product_id integer,
  precio numeric,
  precio_comparacion numeric,
  origen text,
  origen_product_id integer,
  origen_id bigint
)
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
  with prm as (select coalesce(p_at, now()) as t),
  ids as (
    select p.id, p.parent_product_id
      from public.products p
     where p.organization_id = p_organization_id
       and p.id = any (coalesce(p_product_ids, '{}'::integer[]))
  )
  select i.id, x.precio, x.precio_comparacion, x.origen, x.origen_product_id, x.origen_id
    from ids i
    cross join prm
    left join lateral (
      select c.precio, c.precio_comparacion, c.origen, c.origen_product_id, c.origen_id
        from (
          select bp.price as precio, bp.compare_price as precio_comparacion, 'sede'::text as origen,
                 i.id as origen_product_id, bp.id as origen_id, 1 as prioridad, bp.effective_from as desde
            from public.product_branch_prices bp
           where p_branch_id is not null
             and bp.product_id = i.id and bp.branch_id = p_branch_id
             and bp.effective_from <= prm.t and (bp.effective_to is null or bp.effective_to > prm.t)
          union all
          select pp.price, pp.compare_price, 'general', i.id, pp.id::bigint, 2, pp.effective_from
            from public.product_prices pp
           where pp.product_id = i.id
             and pp.effective_from <= prm.t and (pp.effective_to is null or pp.effective_to > prm.t)
          union all
          select bp.price, bp.compare_price, 'padre_sede', i.parent_product_id, bp.id, 3, bp.effective_from
            from public.product_branch_prices bp
           where p_heredar_padre and p_branch_id is not null and i.parent_product_id is not null
             and bp.product_id = i.parent_product_id and bp.branch_id = p_branch_id
             and bp.effective_from <= prm.t and (bp.effective_to is null or bp.effective_to > prm.t)
          union all
          select pp.price, pp.compare_price, 'padre_general', i.parent_product_id, pp.id::bigint, 4, pp.effective_from
            from public.product_prices pp
           where p_heredar_padre and i.parent_product_id is not null
             and pp.product_id = i.parent_product_id
             and pp.effective_from <= prm.t and (pp.effective_to is null or pp.effective_to > prm.t)
        ) c
       order by c.prioridad, c.desde desc, c.origen_id desc
       limit 1
    ) x on true
$$;


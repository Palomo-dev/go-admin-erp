-- =====================================================================
-- Precios y costos por sede (sucursal) para todo tipo de producto.
--
-- Versión PROVISIONAL: el timestamp del nombre se sustituye por la versión
-- real al aplicar con `apply_migration` (ver docs/POLITICA-MIGRACIONES.md).
-- Diseño, resolución e impacto: docs/inventario/PRECIOS-POR-SEDE.md.
--
-- Decisión de modelo (diferente de la propuesta inicial, por qué):
--   La propuesta era añadir `branch_id NULL` a `product_prices` y
--   `product_costs`. Se descartó tras el análisis porque esas tablas las leen
--   y ESCRIBEN filtrando solo por `product_id` (2026-10-05):
--     * ~30 funciones SQL (fn_producto_int_fijar_precio/costo cierran TODAS
--       las filas vivas del producto; assistant_set_product_price cierra «la
--       más reciente»; fn_pos_precio_base_vigente, catálogos, historial…),
--     * los triggers trg_meta_price_sync (enviaría a Meta el precio de una
--       sede como precio del catálogo) y trg_membresias_precio_legado,
--     * ~45 archivos TS del ERP (deshacer del asistente borra/reabre por
--       product_id; el scraper inserta/cierra por product_id),
--     * el repositorio de la web (83 sitios, service role, se despliega
--       DESPUÉS): embebe `product_prices` con `effective_to is null` y toma
--       la más reciente → mostraría y cobraría el precio de una sede como
--       precio general.
--   Con la columna, la primera fila de sede contaminaría todos esos
--   lectores y escritores hasta parchearlos uno a uno. Con tablas propias
--   (`product_branch_prices` / `product_branch_costs`) el precio general
--   sigue en su tabla de siempre, intacto, y SOLO los consumidores que se
--   adaptan explícitamente ven los de sede. Equivale a la propuesta con
--   «branch_id NULL = general» viviendo en `product_prices`/`product_costs`.
--
-- Contenido:
--   1. Tablas product_branch_prices / product_branch_costs (+ coherencia,
--      índices, RLS de lectura por pertenencia; escritura solo por RPC).
--   2. Resolución: fn_precios_vigentes_lote / fn_costos_vigentes_lote y
--      fn_precio_vigente / fn_costo_vigente (SECURITY INVOKER).
--   3. Escritura: fn_productos_sede_fijar (RPC transaccional) y sus
--      auxiliares internas.
--   4. Recetas: fn_receta_costo_teorico_sede; fn_receta_costo y
--      fn_costo_unitario_producto pasan a usar el costo vigente de la sede.
--   5. POS: fn_pos_validar_linea_venta valida contra el precio de la sede de
--      la venta; pos_checkout_v1 le pasa la sede (parche de dos llamadas con
--      guarda md5).
--
-- Retrocompatibilidad: mientras no exista ninguna fila de sede, toda función
-- tocada devuelve exactamente lo de hoy (sede → general; sin sede → general).
-- Herencia hijo→padre: hoy NO existe en el POS ni en su validación; por eso
-- es opcional (`p_heredar_padre`, por defecto false).
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Tablas
-- ---------------------------------------------------------------------
create table if not exists public.product_branch_prices (
  id              bigint generated by default as identity primary key,
  organization_id integer     not null references public.organizations(id) on delete cascade,
  branch_id       integer     not null references public.branches(id) on delete cascade,
  product_id      integer     not null references public.products(id) on delete cascade,
  price           numeric     not null,
  compare_price   numeric,
  effective_from  timestamptz not null default now(),
  effective_to    timestamptz,
  created_at      timestamptz not null default now(),
  created_by      uuid        default auth.uid(),
  constraint product_branch_prices_price_check check (price >= 0),
  constraint product_branch_prices_compare_check check (compare_price is null or compare_price >= 0),
  constraint product_branch_prices_vigencia_check check (effective_to is null or effective_to >= effective_from)
);

create table if not exists public.product_branch_costs (
  id              bigint generated by default as identity primary key,
  organization_id integer     not null references public.organizations(id) on delete cascade,
  branch_id       integer     not null references public.branches(id) on delete cascade,
  product_id      integer     not null references public.products(id) on delete cascade,
  cost            numeric     not null,
  supplier_id     integer     references public.suppliers(id),
  effective_from  timestamptz not null default now(),
  effective_to    timestamptz,
  created_at      timestamptz not null default now(),
  created_by      uuid        default auth.uid(),
  constraint product_branch_costs_cost_check check (cost >= 0),
  constraint product_branch_costs_vigencia_check check (effective_to is null or effective_to >= effective_from)
);


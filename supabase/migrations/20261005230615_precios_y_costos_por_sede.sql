-- ---------------------------------------------------------------------
-- 3. Escritura: fijar precio/costo por sede
-- ---------------------------------------------------------------------
-- Auxiliares internas (mismo algoritmo que fn_producto_int_fijar_precio /
-- _costo, acotado a una sede): anula lo programado después de `desde`,
-- cierra lo que rige en `desde` y abre la nueva fila. NULL = quitar el precio
-- de la sede (vuelve a regir el general). Devuelven true si cambió algo.
create or replace function public.fn_producto_sede_int_fijar_precio(
  p_org integer, p_product_id integer, p_branch_id integer,
  p_precio numeric, p_comparacion numeric, p_desde timestamptz
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_desde timestamptz := coalesce(p_desde, now());
  v_hay boolean;
  v_precio numeric;
  v_comp numeric;
  v_hay_futuros boolean;
begin
  if p_precio is not null and p_precio < 0 then
    raise exception 'precio_negativo' using errcode = '22023';
  end if;
  select true, bp.price, bp.compare_price into v_hay, v_precio, v_comp
    from public.product_branch_prices bp
   where bp.product_id = p_product_id and bp.branch_id = p_branch_id
     and bp.effective_from <= v_desde and (bp.effective_to is null or bp.effective_to > v_desde)
   order by bp.effective_from desc, bp.id desc limit 1;
  v_hay := coalesce(v_hay, false);
  select exists (select 1 from public.product_branch_prices bp
                  where bp.product_id = p_product_id and bp.branch_id = p_branch_id
                    and bp.effective_from > v_desde
                    and (bp.effective_to is null or bp.effective_to > bp.effective_from)) into v_hay_futuros;
  if not v_hay_futuros then
    if not v_hay and p_precio is null then
      return false;
    end if;
    if v_hay and p_precio is not null and v_precio = p_precio
       and coalesce(v_comp, 0) = coalesce(p_comparacion, 0) then
      return false;
    end if;
  end if;
  update public.product_branch_prices bp set effective_to = bp.effective_from
   where bp.product_id = p_product_id and bp.branch_id = p_branch_id
     and bp.effective_from > v_desde
     and (bp.effective_to is null or bp.effective_to > bp.effective_from);
  update public.product_branch_prices bp set effective_to = v_desde
   where bp.product_id = p_product_id and bp.branch_id = p_branch_id
     and bp.effective_from <= v_desde
     and (bp.effective_to is null or bp.effective_to > v_desde);
  if p_precio is not null then
    insert into public.product_branch_prices (organization_id, branch_id, product_id, price, compare_price, effective_from)
    values (p_org, p_branch_id, p_product_id, p_precio, nullif(p_comparacion, 0), v_desde);
  end if;
  return true;
end;
$$;

create or replace function public.fn_producto_sede_int_fijar_costo(
  p_org integer, p_product_id integer, p_branch_id integer,
  p_costo numeric, p_supplier_id integer, p_desde timestamptz

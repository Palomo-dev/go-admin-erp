  select md5(p.prosrc) into v_md5 from pg_proc p where p.oid = v_oid;
  if v_md5 <> '32a99ca1eb51eb44e28a2ed851157094' then
    raise exception 'el parche de pos_checkout_v1 no produjo el cuerpo esperado (md5 %)', v_md5;
  end if;

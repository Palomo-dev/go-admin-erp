-- RPC pública: fija (o quita) el precio o el costo de uno o varios productos
-- en una o varias sedes, en UNA transacción. Con p_incluir_variantes, cada
-- padre arrastra a todas sus variantes no eliminadas.
--   p_tipo: 'precio' | 'costo'
--   p_valor: NULL = quitar el de la sede (rige el general)
--   p_desde: NULL = ahora; no se admite el pasado (cambiaría ventas cerradas)
-- Permisos: los de fn_productos_precio_masivo. Organización: un producto,
-- una sede o un proveedor ajenos rechazan el lote entero (42501).
create or replace function public.fn_productos_sede_fijar(
  p_organization_id integer,
  p_tipo text,
  p_branch_ids integer[],
  p_product_ids integer[],
  p_valor numeric,
  p_comparacion numeric default null,
  p_desde timestamptz default null,
  p_incluir_variantes boolean default false,
  p_supplier_id integer default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_desde timestamptz := coalesce(p_desde, now());
  v_sedes integer[];
  v_pedidos integer[];
  v_productos integer[];
  v_omitidos integer := 0;
  v_p integer;
  v_b integer;
  v_cambio boolean;
  v_cambiados integer := 0;
  v_sin_cambio integer := 0;
begin
  perform public.fn_productos_exigir_permiso(p_organization_id,
    array['inventory.edit', 'product_management', 'inventory_management']);

  if p_tipo is null or p_tipo not in ('precio', 'costo') then
    raise exception 'tipo_invalido' using errcode = '22023';
  end if;
  if p_valor is not null and p_valor < 0 then
    raise exception 'valor_negativo' using errcode = '22023';
  end if;
  if p_comparacion is not null and (p_comparacion < 0 or p_tipo <> 'precio') then
    raise exception 'comparacion_invalida' using errcode = '22023';
  end if;
  if p_supplier_id is not null and p_tipo <> 'costo' then
    raise exception 'proveedor_no_aplica' using errcode = '22023';
  end if;
  if v_desde < now() - interval '5 minutes' then
    raise exception 'desde_en_el_pasado' using errcode = '22023';
  end if;

  select coalesce(array_agg(distinct x order by x), '{}') into v_sedes
    from unnest(coalesce(p_branch_ids, '{}'::integer[])) x where x is not null;
  select coalesce(array_agg(distinct x order by x), '{}') into v_pedidos
    from unnest(coalesce(p_product_ids, '{}'::integer[])) x where x is not null;
  if cardinality(v_sedes) = 0 or cardinality(v_pedidos) = 0 then
    raise exception 'lote_vacio' using errcode = '22023';
  end if;
  if cardinality(v_sedes) > 200 or cardinality(v_pedidos) > 1000 then
    raise exception 'lote_demasiado_grande' using errcode = '22023';
  end if;

  -- Pertenencia: una sola sede, producto o proveedor ajeno rechaza el lote.
  if (select count(*) from public.branches b
       where b.organization_id = p_organization_id and b.id = any (v_sedes)) <> cardinality(v_sedes) then
    raise exception 'sucursal_de_otra_organizacion' using errcode = '42501';
  end if;
  if (select count(*) from public.products p
       where p.organization_id = p_organization_id and p.id = any (v_pedidos)) <> cardinality(v_pedidos) then
    raise exception 'producto_de_otra_organizacion' using errcode = '42501';
  end if;
  if p_supplier_id is not null and not exists (select 1 from public.suppliers s
       where s.id = p_supplier_id and s.organization_id = p_organization_id) then
    raise exception 'proveedor_de_otra_organizacion' using errcode = '42501';
  end if;

  -- Productos efectivos: los pedidos (no eliminados) y, si se pide, sus variantes.
  select coalesce(array_agg(distinct p.id order by p.id), '{}') into v_productos
    from public.products p
   where p.organization_id = p_organization_id
     and coalesce(p.status, 'active') <> 'deleted'
     and (p.id = any (v_pedidos)
          or (p_incluir_variantes and p.parent_product_id = any (v_pedidos)));
  v_omitidos := (select count(*) from public.products p
                  where p.organization_id = p_organization_id and p.id = any (v_pedidos)
                    and coalesce(p.status, 'active') = 'deleted');
  if cardinality(v_productos) * cardinality(v_sedes) > 20000 then
    raise exception 'lote_demasiado_grande' using errcode = '22023';
  end if;

  -- Bloqueo en orden de id: dos escrituras simultáneas no se cruzan.
  perform 1 from public.products p
   where p.id = any (v_productos) and p.organization_id = p_organization_id
   order by p.id
     for update;

  foreach v_p in array v_productos loop
    foreach v_b in array v_sedes loop
      if p_tipo = 'precio' then
        v_cambio := public.fn_producto_sede_int_fijar_precio(p_organization_id, v_p, v_b, p_valor, p_comparacion, v_desde);
      else
        v_cambio := public.fn_producto_sede_int_fijar_costo(p_organization_id, v_p, v_b, p_valor, p_supplier_id, v_desde);
      end if;
      if v_cambio then
        v_cambiados := v_cambiados + 1;
      else
        v_sin_cambio := v_sin_cambio + 1;
      end if;
    end loop;
  end loop;

  return jsonb_build_object(
    'tipo', p_tipo,
    'desde', v_desde,
    'productos', cardinality(v_productos),
    'sedes', cardinality(v_sedes),
    'cambiados', v_cambiados,
    'sin_cambio', v_sin_cambio,
    'omitidos_eliminados', v_omitidos);
end;
$$;


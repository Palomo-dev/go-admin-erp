-- pos_checkout_v1 (43 KB): se cambian SOLO sus dos llamadas a la validación
-- para pasarle la sede. En vez de copiar el cuerpo entero (y arriesgar
-- revertir un cambio ajeno), se parchea el cuerpo vivo con guarda md5:
--   md5 = 8580166ba442c69ad9757f75f613c24d → se aplica el parche
--   md5 = 32a99ca1eb51eb44e28a2ed851157094 → ya aplicado (idempotente)
--   otro → alguien cambió la función después del análisis: se aborta.
-- Llamada 1 (venta nueva): sede del sobre, ya validada contra la organización
--   por pos_checkout_v1; offline acepta también el general.
-- Llamada 2 (mesa): sede de la venta guardada.
do $$
declare
  v_oid regprocedure := 'public.pos_checkout_v1(jsonb)'::regprocedure;
  v_md5 text;
  v_def text;
begin
  select md5(p.prosrc) into v_md5 from pg_proc p where p.oid = v_oid;
  if v_md5 = '32a99ca1eb51eb44e28a2ed851157094' then
    raise notice 'pos_checkout_v1 ya pasa la sede a la validación, nada que hacer';
    return;
  end if;
  if v_md5 is distinct from '8580166ba442c69ad9757f75f613c24d' then
    raise exception 'pos_checkout_v1 cambió desde el análisis (md5 %) · regenerar el parche', v_md5;
  end if;
  v_def := pg_get_functiondef(v_oid);
  v_def := replace(v_def,
    $o1$perform public.fn_pos_validar_linea_venta(v_org, v_actor, v_item, v_hora_precio, p_envelope->'discount_authorization')$o1$ || chr(59),

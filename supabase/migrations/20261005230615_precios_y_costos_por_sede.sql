-- Coherencia: producto, sede (y proveedor) son de la organización de la fila.
create or replace function public.fn_producto_sede_tg_coherencia()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_supplier integer := nullif(to_jsonb(new)->>'supplier_id', '')::integer;
begin
  if not exists (select 1 from public.products p
                  where p.id = new.product_id and p.organization_id = new.organization_id) then
    raise exception 'producto_de_otra_organizacion' using errcode = '23514',
      detail = format('El producto %s no es de la organización %s.', new.product_id, new.organization_id);
  end if;
  if not exists (select 1 from public.branches b
                  where b.id = new.branch_id and b.organization_id = new.organization_id) then
    raise exception 'sucursal_de_otra_organizacion' using errcode = '23514',
      detail = format('La sede %s no es de la organización %s.', new.branch_id, new.organization_id);
  end if;
  if v_supplier is not null and not exists (select 1 from public.suppliers s
                  where s.id = v_supplier and s.organization_id = new.organization_id) then
    raise exception 'proveedor_de_otra_organizacion' using errcode = '23514',
      detail = format('El proveedor %s no es de la organización %s.', v_supplier, new.organization_id);
  end if;
  return new;
end;
$$;
revoke all on function public.fn_producto_sede_tg_coherencia() from public, anon, authenticated;

create or replace trigger trg_product_branch_prices_coherencia
  before insert or update of organization_id, branch_id, product_id on public.product_branch_prices
  for each row execute function public.fn_producto_sede_tg_coherencia();


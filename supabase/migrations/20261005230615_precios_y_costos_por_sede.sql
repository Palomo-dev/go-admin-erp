    from public.product_branch_costs bc
   where bc.product_id = p_product_id and bc.branch_id = p_branch_id
     and bc.effective_from <= v_desde and (bc.effective_to is null or bc.effective_to > v_desde)
   order by bc.effective_from desc, bc.id desc limit 1;
  v_hay := coalesce(v_hay, false);
  select exists (select 1 from public.product_branch_costs bc
                  where bc.product_id = p_product_id and bc.branch_id = p_branch_id
                    and bc.effective_from > v_desde
                    and (bc.effective_to is null or bc.effective_to > bc.effective_from)) into v_hay_futuros;
  if not v_hay_futuros then
    if not v_hay and p_costo is null then
      return false;
    end if;
    if v_hay and p_costo is not null and v_costo = p_costo
       and v_supplier is not distinct from coalesce(p_supplier_id, v_supplier) then
      return false;
    end if;
  end if;
  update public.product_branch_costs bc set effective_to = bc.effective_from
   where bc.product_id = p_product_id and bc.branch_id = p_branch_id
     and bc.effective_from > v_desde
     and (bc.effective_to is null or bc.effective_to > bc.effective_from);
  update public.product_branch_costs bc set effective_to = v_desde
   where bc.product_id = p_product_id and bc.branch_id = p_branch_id
     and bc.effective_from <= v_desde
     and (bc.effective_to is null or bc.effective_to > v_desde);
  if p_costo is not null then
    insert into public.product_branch_costs (organization_id, branch_id, product_id, cost, supplier_id, effective_from)
    values (p_org, p_branch_id, p_product_id, p_costo, p_supplier_id, v_desde);
  end if;
  return true;
end;
$$;


-- 4. Recetas y costo unitario por sede
-- ---------------------------------------------------------------------
-- Costo teórico de una receta en una sede: Σ (cantidad bruta en unidad del
-- insumo × costo vigente del insumo en la sede). Las cantidades salen de
-- fn_receta_int_calcular (la misma regla de merma y de conversión de unidad
-- que descuenta el stock: bruta = neta / (1 − merma/100)); no se recalculan.
-- A diferencia de fn_receta_costo, NO usa el costo promedio del inventario:
-- es el costo de catálogo de la sede.
create or replace function public.fn_receta_costo_teorico_sede(
  p_organization_id integer,
  p_branch_id integer,
  p_recipe_id integer,
  p_at timestamptz default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_at timestamptz := coalesce(p_at, now());
  v_rec jsonb;
  v_ver boolean;
  v_rinde numeric;
  v_lineas jsonb;
  v_tanda numeric;
  v_sin integer;
  v_err integer;
begin
  perform public.fn_assert_acceso_org(p_organization_id);
  if p_branch_id is not null and not exists (
       select 1 from public.branches b where b.id = p_branch_id and b.organization_id = p_organization_id) then
    raise exception 'sucursal_invalida' using errcode = '22023';
  end if;
  v_rec := public.fn_receta_int_a_jsonb(p_recipe_id);
